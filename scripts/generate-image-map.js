#!/usr/bin/env node
/**
 * Generates src/data/imageMap.ts — a static map of image key → require()
 * so Metro can bundle every disc PNG at build time.
 *
 * Run: node scripts/generate-image-map.js
 */

const fs = require('fs');
const path = require('path');

const IMAGES_DIR = path.join(__dirname, '..', 'assets', 'disc-images');
const OUT_PATH   = path.join(__dirname, '..', 'src', 'data', 'imageMap.ts');

const pngs = fs.readdirSync(IMAGES_DIR)
  .filter(f => f.endsWith('.png'))
  .sort();

const lines = pngs.map(file => {
  const key = file.replace('.png', '');
  // Path is relative from src/data/ to assets/disc-images/
  return `  '${key}': require('../../assets/disc-images/${file}'),`;
});

const output = `// Auto-generated by scripts/generate-image-map.js — do not edit manually
const images: Record<string, ReturnType<typeof require>> = {
${lines.join('\n')}
};
export default images;
`;

fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
fs.writeFileSync(OUT_PATH, output);
console.log(`Wrote ${pngs.length} entries to ${OUT_PATH}`);
